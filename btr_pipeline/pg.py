# Columns added after the first PostgreSQL release go here as
# (table, column, type); applied with ADD COLUMN IF NOT EXISTS.
ADDED_COLUMNS: list[tuple[str, str, str]] = []

# Tables in foreign-key order (parents first), used by the copy tool.
TABLES = ["documents", "btr_measures", "ndc_quotes", "ndc_measures", "measure_matches"]


def init_schema(conn: PGConnection, view_sql: str) -> None:
    for stmt in SCHEMA:
        conn.execute(stmt)
    for table, column, coltype in ADDED_COLUMNS:
        conn.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {coltype}")
    conn.execute("DROP VIEW IF EXISTS measures_view")
    conn.execute(view_sql)
    conn.commit()


def reset_identities(conn: PGConnection) -> None:
    """Move every identity sequence past the highest id (after copying rows with explicit ids)."""
    for table in TABLES:
        conn.execute(
            f"SELECT setval(pg_get_serial_sequence('{SCHEMA_NAME}.{table}', 'id'), "
            f"COALESCE((SELECT MAX(id) FROM {table}), 0) + 1, false)"
        )
    conn.commit()


_ROLE_NAME = re.compile(r"^[a-z_][a-z0-9_]{0,62}$")


def create_app_role(conn: PGConnection, role: str, password: str) -> bool:
    """
    Create (or update the password of) the login role the hosted app uses:
    read/write access to the rows of the `btr` schema, no rights to change
    the schema itself. Returns True if the role was newly created.
    """
    from psycopg import sql

    if not _ROLE_NAME.match(role):
        raise ValueError(f"Invalid role name: {role!r}")

    def run(stmt) -> None:
        conn.execute(stmt.as_string(conn))

    exists = conn.execute("SELECT 1 FROM pg_roles WHERE rolname = ?",
                          (role,)).fetchone()
    ident = sql.Identifier(role)
    if exists:
        run(sql.SQL("ALTER ROLE {} WITH LOGIN PASSWORD {}")
            .format(ident, sql.Literal(password)))
    else:
        run(sql.SQL("CREATE ROLE {} WITH LOGIN PASSWORD {}")
            .format(ident, sql.Literal(password)))

    database = conn.execute("SELECT current_database()").fetchone()[0]
    schema = sql.Identifier(SCHEMA_NAME)
    run(sql.SQL("GRANT CONNECT ON DATABASE {} TO {}")
        .format(sql.Identifier(database), ident))
    run(sql.SQL("GRANT USAGE ON SCHEMA {} TO {}").format(schema, ident))
    run(sql.SQL("GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA {} TO {}")
        .format(schema, ident))
    run(sql.SQL("GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA {} TO {}")
        .format(schema, ident))
    # Tables added later by init-db inherit the same rights.
    run(sql.SQL("ALTER DEFAULT PRIVILEGES IN SCHEMA {} "
                "GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO {}")
        .format(schema, ident))
    run(sql.SQL("ALTER DEFAULT PRIVILEGES IN SCHEMA {} "
                "GRANT USAGE, SELECT ON SEQUENCES TO {}")
        .format(schema, ident))
    conn.commit()
    return not exists
