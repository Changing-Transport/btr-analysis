"""
PostgreSQL backend for the BTR database.

The pipeline and the review app are written against SQLite's DB-API dialect
(`?` placeholders, rows readable by index and by column name). This module
lets the same code run on Azure Database for PostgreSQL by giving it a
connection with the same surface:

* `?` placeholders are rewritten to `%s` (outside string literals), and
  literal `%` is escaped when parameters are passed.
* Three SQLite-only constructs used in this codebase are rewritten:
    - `GROUP_CONCAT(DISTINCT x)`        -> `string_agg(DISTINCT x, ',')`
    - `INSERT OR IGNORE INTO ... `      -> `INSERT INTO ... ON CONFLICT DO NOTHING`
  Anything else must be written in SQL both engines understand. New queries
  should avoid SQLite-specific functions rather than extend this list.
* Rows support `row[0]`, `row["column"]`, iteration and `row.keys()`, like
  `sqlite3.Row`.

All tables live in the `btr` schema (set via search_path), so the shared
database can hold the Tracker's own `ndc` and `ref` schemas next to it.
"""

import re

import psycopg

SCHEMA_NAME = "btr"

_GROUP_CONCAT = re.compile(r"GROUP_CONCAT\(\s*DISTINCT\s+([^()]+?)\s*\)", re.IGNORECASE)
_INSERT_OR_IGNORE = re.compile(r"INSERT\s+OR\s+IGNORE\s+INTO", re.IGNORECASE)


def translate(sql: str, has_params: bool) -> str:
    """Rewrite a SQLite-dialect statement for psycopg/PostgreSQL."""
    ignore = bool(_INSERT_OR_IGNORE.search(sql))
    sql = _GROUP_CONCAT.sub(r"string_agg(DISTINCT \1, ',')", sql)
    sql = _INSERT_OR_IGNORE.sub("INSERT INTO", sql)
    if ignore:
        sql = sql.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"

    if not has_params:
        return sql

    out = []
    in_literal = False
    for ch in sql:
        if ch == "'":
            in_literal = not in_literal
            out.append(ch)
        elif ch == "%":
            out.append("%%")
        elif ch == "?" and not in_literal:
            out.append("%s")
        else:
            out.append(ch)
    return "".join(out)


class Row:
    """Read-only row addressable by position or column name (like sqlite3.Row)."""

    __slots__ = ("_values", "_index")

    def __init__(self, values, index: dict[str, int]):
        self._values = tuple(values)
        self._index = index

    def __getitem__(self, key):
        if isinstance(key, str):
            return self._values[self._index[key]]
        return self._values[key]

    def __iter__(self):
        return iter(self._values)

    def __len__(self):
        return len(self._values)

    def __eq__(self, other):
        if isinstance(other, Row):
            return self._values == other._values
        return self._values == tuple(other)

    def __hash__(self):
        return hash(self._values)

    def __repr__(self):
        return f"Row({dict(zip(self._index, self._values))!r})"

    def keys(self) -> list[str]:
        return list(self._index)


def _row_factory(cursor):
    if cursor.description is None:
        return lambda values: values
    index = {col.name: i for i, col in enumerate(cursor.description)}
    return lambda values: Row(values, index)


class PGConnection(psycopg.Connection):
    """psycopg connection accepting SQLite-dialect statements."""

    dialect = "postgres"

    def execute(self, query, params=None, **kwargs):
        has_params = bool(params)
        return super().execute(translate(query, has_params),
                               params if has_params else None, **kwargs)

    def executemany(self, query, params_seq):
        with self.cursor() as cur:
            cur.executemany(translate(query, True), params_seq)


def connect(url: str) -> PGConnection:
    return PGConnection.connect(
        url,
        row_factory=_row_factory,
        options=f"-c search_path={SCHEMA_NAME},public",
    )


